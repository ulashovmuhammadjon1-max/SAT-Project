# AP HUMAN GEOGRAPHY 4.10 Consequences of Centrifugal and Centripetal Forces
# -- 30 questions.
# CED Course Framework V.1, Unit 4. Enduring understanding SPS-4, "Political,
# economic, cultural, or technological changes can challenge state
# sovereignty." Learning objective SPS-4.C, "Explain how the concepts of
# centrifugal and centripetal forces apply at the state scale."
#
# Essential knowledge -- two statements, and both are lists of CONSEQUENCES:
#   SPS-4.C.1  Centrifugal forces may lead to failed states, uneven development,
#              stateless nations, and ethnic nationalist movements.
#   SPS-4.C.2  Centripetal forces can lead to ethnonationalism, more equitable
#              infrastructure development, and increased cultural cohesion.
#
# WHAT THIS TOPIC IS AND IS NOT. It is not a topic about what centrifugal and
# centripetal forces ARE -- that vocabulary arrives earlier in the unit. Both
# statements are lists of what the forces LEAD TO. So every item here asks about
# an outcome, and an item that merely asked a student to classify a force as
# centrifugal or centripetal would be testing the previous topic instead. Items
# 1, 2 and 30 make the direction of the reasoning explicit.
#
# THE ASYMMETRY THAT DECIDES THIS MODULE. The CED puts ETHNIC NATIONALIST
# MOVEMENTS on the centrifugal list and ETHNONATIONALISM on the centripetal one.
# That looks like a contradiction and is not:
#   - A minority nation's ethnic nationalist movement inside a larger state
#     pulls AWAY from that state, so it is a centrifugal outcome.
#   - Ethnonationalism that identifies the whole state with one nation binds
#     that nation's members TO the state, so it is a centripetal outcome.
# The same material -- an ethnic identity attached to a territory -- produces
# either outcome depending on whether the identity is coextensive with the state
# or contained inside it. Items 5, 12, 18, 22 and 27 rest on this, and item 18
# asks for the distinction directly. Item 22 records the cost the CED does not
# state: ethnonationalism binds the majority centripetally and can be
# centrifugal for a minority in the same state at the same time.
#
# THE SECOND PAIRING is uneven development against more equitable
# infrastructure development. The two statements name these as opposites, and
# infrastructure is where the abstraction becomes visible on the ground: roads,
# power, water and schools are either spread across the state's regions or
# concentrated in some of them. Items 8, 9, 15, 20, 26 and 28 read the forces off
# that distribution, which is what makes the topic geographic rather than merely
# political.
#
# "MAY LEAD TO" and "CAN LEAD TO". Neither statement asserts that the outcome
# follows. Items 10, 23 and 30 are keyed against the stronger reading.
#
# SCALE. The learning objective says "at the state scale", and the same force can
# be centripetal at one scale and centrifugal at another -- a regional identity
# that unites a province divides the state containing it. Items 6, 16, 22 and 29
# are scale items, which is the CED's own suggested skill for this topic.
#
# NO REAL COUNTRY IS NAMED. Neither statement names one, failed states and
# stateless nations are politically live categories, and describing a situation
# tests the same understanding without asserting a contested claim.
#
# Three items carry a real `table=`. FIVE choices (A-E).
