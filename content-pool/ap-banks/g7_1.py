# AP HUMAN GEOGRAPHY 7.1 The Industrial Revolution -- 30 questions
# CED Course Framework V.1, Unit 7. Enduring understanding SPS-7,
# "Industrialization, past and present, has facilitated improvements in
# standards of living, but it has also contributed to geographically uneven
# development." Learning objective SPS-7.A, "Explain how the Industrial
# Revolution facilitated the growth and diffusion of industrialization."
#
# Essential knowledge -- three statements, and they run in sequence:
#   SPS-7.A.1  Industrialization began as a result of new technologies and was
#              facilitated by the availability of natural resources.
#   SPS-7.A.2  As industrialization spread it caused food supplies to increase
#              and populations to grow; it allowed workers to seek new industrial
#              jobs in the cities and changed class structures.
#   SPS-7.A.3  Investors in industry sought out more raw materials and new
#              markets, a factor that contributed to the rise of colonialism and
#              imperialism.
#
# THE SEQUENCE IS: technology and resources make industrialization possible
# (A.1); industrialization then reorganizes food, population, work and class
# (A.2); and the search for inputs and outlets carries it outward (A.3). Item 30
# keys on the sequence, and each statement's own internal structure is what the
# items in its group test.
#
# SPS-7.A.1 NAMES TWO DIFFERENT KINDS OF CAUSE and the CED weights them
# differently: technology is what industrialization BEGAN AS A RESULT OF, while
# natural resources FACILITATED it. Item 2 keys on that asymmetry. A resource is
# useless without a technology that can use it -- coal was under the ground for
# the whole of human history -- and a technology is useless without the resource
# it consumes. The verbs record which of the two was the new thing.
#
# SPS-7.A.2 IS A FOUR-PART CONSEQUENCE and every part gets an item: food supplies
# increase, populations grow, workers move to industrial jobs in cities, and
# class structures change. The middle two connect this topic to Topic 5.4's
# second agricultural revolution and to the demographic transition model, and
# items 10 and 11 make those connections explicit rather than leaving a student
# to meet the same chain twice without recognizing it.
#
# SPS-7.A.3'S HEDGE IS THE MOST IMPORTANT WORDING IN THE TOPIC. The CED says the
# search for raw materials and new markets was "A FACTOR THAT CONTRIBUTED TO" the
# rise of colonialism and imperialism. It is not "the cause" and not "the reason".
# Items 14, 20 and 30 are keyed against the stronger reading, and item 20 asks
# for the distinction directly, because a key asserting a single cause for
# colonialism would be asserting something the framework declines to.
#
# NO REAL COUNTRY IS NAMED ANYWHERE IN THIS MODULE, and no date is attached to
# any named place. Which regions industrialized when is a matter of real
# political history that the CED does not set out here, and the mechanisms can be
# taught without it. The three data items use unnamed economies.
#
# Three items carry a real `table=`. FIVE choices (A-E).
