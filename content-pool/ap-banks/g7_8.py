# AP HUMAN GEOGRAPHY 7.8 Sustainable Development -- 30 questions
# CED Course Framework V.1, Unit 7. Enduring understanding IMP-7,
# "Environmental problems stemming from industrialization MAY BE REMEDIED
# through sustainable development strategies." Learning objective IMP-7.A,
# "Explain how sustainability principles relate to and impact industrialization
# and spatial development." Suggested skill 5.D, "Explain the DEGREE TO WHICH a
# geographic concept, process, model, or theory effectively explains geographic
# effects across various geographic scales."
#
# Essential knowledge -- three statements:
#   IMP-7.A.1  Sustainable development policies ATTEMPT to remedy problems
#              stemming from natural-resource depletion, mass consumption, the
#              effects of pollution, and the impact of climate change.
#   IMP-7.A.2  Ecotourism is tourism based in natural environments -- OFTEN
#              environments that are threatened by LOOMING industrialization or
#              development -- that FREQUENTLY helps to protect the environment
#              in question WHILE ALSO providing jobs for the local population.
#   IMP-7.A.3  The UN's Sustainable Development Goals HELP MEASURE progress in
#              development, such as small-scale finance and public
#              transportation projects.
# and one further CED sentence, from the unit 7 overview on page 121: "Students
# explore strategies for sustainable development focused on women, children,
# health, education, the environment, and global cooperation." Item 9 rests on
# that sentence and cites it.
#
# THIS TOPIC IS BUILT ALMOST ENTIRELY OUT OF HEDGES, and they are the content
# rather than decoration. Five of them, each keyed on directly:
#   MAY BE REMEDIED    (IMP-7)      item 1
#   ATTEMPT TO REMEDY  (IMP-7.A.1)  item 3
#   OFTEN threatened   (IMP-7.A.2)  item 12
#   FREQUENTLY helps   (IMP-7.A.2)  item 14
#   HELP MEASURE       (IMP-7.A.3)  item 21
# A student who reads any of them as a flat assertion has learned that
# sustainable development works, which the framework does not say. Every one of
# those items' distractors is a way of over-reading the hedge, and one is a way
# of under-reading it into the claim that nothing works at all.
#
# IMP-7.A.1 NAMES FOUR PROBLEMS AND THEY ARE FOUR, NOT ONE. Items 4 to 7 take
# one each. Two of them are named in a particular form that the module keeps:
# the statement says "the EFFECTS of pollution" and "the IMPACT of climate
# change", not pollution and climate change as such. Items 6 and 7 ask what that
# wording does, because a policy addresses what a process does to a place rather
# than the process in the abstract.
#
# ECOTOURISM IS FRESH IN THIS BANK. No other module in HUMAN_GEO uses the word.
# IMP-7.A.2 is one sentence with four separable clauses -- what it is, where it
# often is, what it frequently does, and for whom -- and items 11 to 18 take
# them apart. Item 15 supplies the mechanism the CED does not state (the
# environment is the asset that earns the income) and says so in its `why`.
#
# WHAT WAS ALREADY TAKEN, AND HOW THIS MODULE STEERS AROUND IT:
#   g1_5 q8 already asks "Which definition of sustainability best matches the
#   way the concept is used in this course?", so no item here defines
#   sustainability. g6_11 covers urban sustainability challenges and responses
#   in fifteen items -- sprawl, sanitation, air and water quality, ecological
#   footprint, brownfields, growth boundaries -- all inside the city. Nothing
#   here repeats them: this topic's scale is the industrial economy and the
#   world, not the metropolitan area, and item 23 is the item that says so.
#
# SUGGESTED SKILL 5.D ASKS FOR THE DEGREE TO WHICH SOMETHING WORKS ACROSS
# SCALES, which is stronger than asking what it is. Items 18, 23 and 24 are that
# skill: ecotourism reaching a site and a local economy but not a global total,
# policies whose scale and whose problem's scale do not match, and the
# relocation of an activity improving a local record while changing no global
# one.
#
# NO REAL COUNTRY, PLACE, SITE OR PROJECT IS NAMED ANYWHERE IN THIS MODULE, and
# no goal of the UN's Sustainable Development Goals is quoted or numbered,
# because the CED quotes and numbers none. The three data items carry
# hypothetical records attached to an unnamed protected site, an unnamed
# district and four unnamed economies.
#
