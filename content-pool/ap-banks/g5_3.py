# has changed over time because of cultural diffusion and advances in
# technology." Two learning objectives:
#   SPS-5.A  Identify major centers of domestication of plants and animals.
#   SPS-5.B  Explain how plants and animals diffused globally.
#
# Essential knowledge -- one statement each:
#   SPS-5.A.1  Early hearths of domestication of plants and animals arose in the
#              Fertile Crescent and several other regions of the world,
#              including the Indus River Valley, Southeast Asia, and Central
#              America.
#   SPS-5.B.1  Patterns of diffusion, such as the Columbian Exchange and the
#              agricultural revolutions, resulted in the global spread of
#              various plants and animals.
#
# WHAT THIS MODULE WILL AND WILL NOT ASSERT. The CED names four hearths and two
# patterns of diffusion and attaches no crop to any hearth and no date to any of
# them. So:
#   - Crop-to-hearth attributions appear only where they are not in scholarly
#     dispute: wheat and barley with the Fertile Crescent, maize, beans and
#     squash with Central America, rice with Southeast Asia. NOTHING is
#     attributed to the Indus River Valley beyond the CED's own sentence naming
#     it as a hearth, because the attributions available there are contested and
#     a wrong key would teach the error.
#   - NO DATE is attached to a named hearth anywhere. Item 27 uses four
#     unlabelled hearths precisely so that the reasoning about sequence can be
#     tested without asserting an archaeological date the CED never gives.
#   - Columbian Exchange directions are used only for organisms whose hemisphere
#     of origin is settled: maize, potatoes, tomatoes and cacao from the
#     Americas; wheat, rice, sugarcane, coffee, cattle, pigs and horses from the
#     Old World.
#
# THE WORD "SEVERAL" IN SPS-5.A.1 is doing real work and item 29 keys on it. The
# statement says hearths arose in the Fertile Crescent AND SEVERAL OTHER
# REGIONS, which asserts multiple INDEPENDENT origins rather than one origin
# followed by diffusion everywhere. That is the difference between the two
# learning objectives of this topic: SPS-5.A is about where agriculture began,
# in the plural, and SPS-5.B is about how its products then travelled.
#
# THE DIRECTION OF THE COLUMBIAN EXCHANGE is the single most reversible fact in
# the topic, because the crops that became staples of Old World diets came FROM
# the Americas while the livestock that reshaped American landscapes came FROM
# the Old World. Items 10, 11, 12, 13, 26 and 28 are built on that crossing.
#
