# Essential knowledge, in full -- two statements:
#   IMP-4.C.1  Forms of governance include unitary states and federal states.
#   IMP-4.D.1  Unitary states tend to have a more top-down, centralized form of
#              governance, while federal states have more locally based,
#              dispersed power centers.
#
# IMP-4.C.1 supplies the two categories and IMP-4.D.1 supplies the difference
# between them. Note the CED's own hedge: unitary states TEND TO have a more
# centralized form. The comparison is one of degree along a spectrum rather than
# a binary switch, and items 5, 11, 19 and 22 turn on that hedge, because a
# module presenting the two as opposites would be overstating the sentence.
#
# The distinction as this module uses it, since the CED supplies only the two
# adjectives:
#   unitary state  authority is held at the centre and any powers exercised
#                  locally are DELEGATED, so the centre can alter or withdraw
#                  them by ordinary decision
#   federal state  authority is DIVIDED between a central government and
#                  regional governments, each with powers the other cannot
#                  simply take away, usually because the division is
#                  constitutional
# The operative test is therefore not how much power regions currently exercise
# but WHERE THE POWER COMES FROM and who can withdraw it. A unitary state may
# devolve a great deal and still be unitary; a federal state may have weak
# regions and still be federal. Items 4, 9, 14, 20 and 27 all rest on that test,
# and item 9 asks for it directly.
#
# THE SPATIAL CONSEQUENCE is what makes this geography rather than civics, and
# IMP-4.D.1 states it in the words "dispersed power centers". A federal
# arrangement produces multiple capitals, multiple legislatures, multiple sets
# of law and multiple places where a decision can be made. A unitary
# arrangement concentrates all of that at one point. Items 6, 13, 17, 24, 26 and
# 28 are keyed to that spatial reading.
#
# NO COUNTRY IS NAMED ANYWHERE IN THIS MODULE. Constitutional arrangements
# change, several real states are genuinely hard to classify, and the CED names
# none here. Describing an arrangement and asking which category it fits tests
# the same understanding without asserting a fact about a real state that could
# be out of date or contested.
#
# Three items carry a real `table=`. FIVE choices (A-E).
