# AP HUMAN GEOGRAPHY 4.8 Defining Devolutionary Factors -- 30 questions
# CED Course Framework V.1, Unit 4. Enduring understanding SPS-4, "Political,
# economic, cultural, or technological changes can challenge state
# sovereignty." Learning objective SPS-4.A, "Define factors that lead to the
# devolution of states."
#
# Essential knowledge -- one statement, and it is a closed list of six:
#   SPS-4.A.1  Factors that can lead to the devolution of states include the
#              division of groups by physical geography, ethnic separatism,
#              ethnic cleansing, terrorism, economic and social problems, and
#              irredentism.
#
# The six factors, defined here because the CED defines none of them:
#   division of groups by physical geography
#                       mountains, water, deserts or sheer distance separating a
#                       region from the state's core, so that contact with the
#                       centre is weaker than contact within the region
#   ethnic separatism   a distinct ethnic group within a state seeking greater
#                       autonomy or full independence for its territory
#   ethnic cleansing    the forced removal of an ethnic group from a territory
#                       by violence or intimidation, in order to make that
#                       territory ethnically uniform
#   terrorism           violence directed at civilians to advance a political
#                       aim, including the aim of separation
#   economic and social problems
#                       unemployment, deprivation, and unequal treatment
#                       concentrated in one region, which turn a regional
#                       grievance into a case for separate government
#   irredentism         a claim by a state or group to territory across a border
#                       that is inhabited by people it regards as its own
#
# THE TERM DEVOLUTION ITSELF is defined in Topic 4.9's statement, not here: it
# is the fragmentation of a state into autonomous regions, or its
# disintegration. This topic asks only what CAUSES it, which is why every item
# here is about a factor and not about an outcome.
#
# THE DIRECTION IRREDENTISM POINTS is the one students reverse. Separatism is
# INTERNAL: a group inside a state wants out. Irredentism is EXTERNAL: a
# neighbouring state or a group wants territory that currently belongs to
# someone else, because its own people live there. The two can operate on the
# same border at the same time, which is what items 8, 13, 20 and 27 are built
# on.
#
# HANDLING ETHNIC CLEANSING. The CED names it and this module names it
# accurately -- forced removal of a population from a territory -- without
# describing atrocities. It appears as a factor in the devolutionary process and
# as a consequence of it, since the two run together, and no item asks a student
# to evaluate it.
#
# NO REAL COUNTRY IS NAMED. The CED names none in this statement, real cases are
# politically live, and describing a situation and asking which factor it
# illustrates tests the same understanding without asserting a contested claim.
#
# Three items carry a real `table=`. FIVE choices (A-E).
