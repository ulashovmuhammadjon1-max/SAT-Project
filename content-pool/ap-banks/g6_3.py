# AP HUMAN GEOGRAPHY 6.3 Cities and Globalization -- 30 questions
# CED Course Framework V.1, Unit 6. Enduring understanding PSO-6, "The presence
# and growth of cities vary across geographical locations because of physical
# geography and resources." Learning objective PSO-6.B, "Explain how cities
# embody processes of globalization." Suggested skill 5.B, explain spatial
# relationships across various geographic scales.
#
# Essential knowledge -- two statements:
#   PSO-6.B.1  World cities function at the top of the world's urban hierarchy
#              and drive globalization.
#   PSO-6.B.2  Cities are connected globally by networks and linkages and
#              mediate global processes.
#
# THE ONE IDEA THAT MAKES THIS TOPIC DIFFICULT is that world city status is NOT
# a matter of population. The CED says world cities function AT THE TOP OF THE
# WORLD'S URBAN HIERARCHY, and a hierarchy of function is not a ranking by size.
# What puts a city at the top is the decisions taken there and the services
# supplied from there -- corporate command, finance, law, accounting,
# advertising, consulting, media -- because those reach far beyond the city
# itself. A very large city can sit low in that hierarchy and a moderately sized
# one can sit near its top. Items 4, 17 and 27 are built on this, and item 27's
# table is constructed so that population and world-city standing rank the four
# cities in DIFFERENT orders, which is the whole point of the item.
#
# "MEDIATE GLOBAL PROCESSES" IS PSO-6.B.2'S HARDEST PHRASE. To mediate is to be
# the place through which something passes and is acted on. A global financial
# movement, a cultural trend or a supply-chain decision does not float free: it
# is decided in an office, priced on an exchange, filmed in a studio, routed
# through an exchange point -- all of which are in particular cities. Items 9,
# 10, 21 and 22 walk that idea, and item 9 asks for it directly.
#
# NETWORKS AND LINKAGES, since PSO-6.B.2 names them without listing them. The
# flows that link cities are capital, information, people and goods, and each
# leaves a measurable trace -- office networks, data routes, air links, port
# traffic. Item 23 makes the structural point that a network is nodes plus the
# links between them, so a city's position depends on what it is connected TO
# and not only on what is in it.
#
# THE COUNTER-INTUITIVE CONSEQUENCE, which is item 12 and item 28: a world city
# can be more tightly connected to world cities on other continents than to the
# medium cities of its own country. That is what "connected globally by networks"
# means when it is taken seriously, and it is why the suggested skill for this
# topic is scale analysis -- item 13 keys on a city being local and global at
# once.
#
# NO REAL CITY IS NAMED ANYWHERE IN THIS MODULE, the three data items included.
# World city rankings are compiled by particular research groups on particular
# criteria and they change; naming a city as top-tier would be asserting one
# group's current judgement as a fact.
#
