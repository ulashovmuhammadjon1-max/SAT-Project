# THE WORDS "SOME CASES" AND "OFTEN" ARE LOAD-BEARING. KC-6.2.III.A.ii says
# redrawn boundaries led to conflict and displacement IN SOME CASES, not in all;
# KC-6.3.I.C says governments OFTEN took a strong role, not always. Items 4, 8,
