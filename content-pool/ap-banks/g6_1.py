# AP HUMAN GEOGRAPHY 6.1 The Origin and Influences of Urbanization -- 30 questions
# CED Course Framework V.1, Unit 6. Enduring understanding PSO-6, "The presence
# and growth of cities vary across geographical locations because of physical
# geography and resources." Learning objective PSO-6.A, "Explain the processes
# that initiate and drive urbanization and suburbanization."
#
# Essential knowledge -- the two statements assigned to this topic:
#   PSO-6.A.1  Site and situation influence the origin, function, and growth of
#              cities.
#   PSO-6.A.2  Changes in transportation and communication, population growth,
#              migration, economic development, and government policies
#              influence urbanization.
#
# SITE AGAINST SITUATION IS THE WHOLE OF THE FIRST STATEMENT, and the CED
# defines neither. The definitions used throughout, and stated in every claim
# that depends on them:
#
#   SITE       the ABSOLUTE, physical characteristics of the place itself --
#              terrain, water supply, soil, climate, defensibility, buildable
#              ground. What is there.
#   SITUATION  the RELATIVE position of the place -- where it stands with respect
#              to routes, resources, other settlements and markets. What it is
#              near, and what passes through it.
#
# The operative test, and the one items 4, 19 and 28 apply: a site attribute can
# be described without mentioning any other place, and a situation attribute
# cannot. A natural harbour is site; being the nearest port to a wheat-growing
# interior is situation. Both can change -- items 21 and 22 -- and situation can
# change WITHOUT THE CITY MOVING, which is the property that makes it the more
# powerful of the two for explaining rise and decline.
#
# PSO-6.A.2 IS A CLOSED LIST OF FIVE and items 11 to 17 walk it: changes in
# transportation and communication (which the CED pairs, so items 11 and 12 take
# one each), population growth, migration, economic development, and government
# policies. Item 17 tests the boundary of the list. Nothing else is keyed as a
# driver of urbanization anywhere in this module.
#
# ONE DISTINCTION THE DATA ITEMS DEPEND ON, and item 24 asks for directly:
# URBANIZATION is the rising SHARE of a population living in cities, which is a
# proportion. It is not the same as growth in the NUMBER of city dwellers, and
# the two can move in opposite directions when total population is changing. A
# student who reads urbanization as "cities got bigger" will misread every table
# in Unit 6.
#
# NO REAL CITY IS NAMED ANYWHERE IN THIS MODULE. Site and situation arguments
# about real cities are contestable and often stale, and describing a place tests
# the same reasoning.
#
# Three items carry a real `table=`. FIVE choices (A-E).
