# AP HUMAN GEOGRAPHY 4.3 Political Power and Territoriality -- 30 questions
# CED (2020 framework), Unit 4, enduring understanding PSO-4.
# Learning objective PSO-4.C: describe the concepts of political power and
# territoriality as used by geographers.
#
# Essential knowledge:
#   PSO-4.C.1  Political power is expressed geographically as control over
#              people, land, and resources, as illustrated by neocolonialism,
#              shatterbelts, and choke points.
#   PSO-4.C.2  Territoriality is the connection of people, their culture, and
#              their economic systems to the land.
#
# PSO-4.C.1 gives three illustrations and no more, so the module works through
# them one at a time and then asks students to tell them apart: neocolonialism is
# control exercised through economy after formal rule ends, a shatterbelt is a
# REGION caught between competing external powers, and a choke point is a NARROW
# PASSAGE whose control confers leverage far beyond its size. Items 14, 19 and 27
# are the discrimination items.
#
# Territoriality in PSO-4.C.2 is deliberately broader than "owning land": the
# framework's wording joins people, their CULTURE, and their ECONOMIC SYSTEMS to
# the land, so items 20-26 include sacred sites and resource-use customs, not
# only fences and deeds.
#
# Suggested skill 5.B, explain spatial relationships across scales: items 11, 22
# and 29 carry real data tables; scale-of-analysis items are 4, 24 and 30.
#
# Neocolonialism appears in Topic 4.2 as a process; here it is treated as an
# EXPRESSION OF POWER, which is the angle PSO-4.C.1 takes on it, and no stem is
# repeated between the two modules.
#
