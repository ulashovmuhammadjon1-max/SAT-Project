# WHAT THIS TOPIC IS ABOUT, as against 4.3: 4.3 asks what KIND of party system a
# country has and which rules produce it. 4.4 asks what the party system DOES --
# how it carries, or fails to carry, a citizen's participation into policy. That
# is why PAU-4.B.2 is a two-way statement: a party system shapes participation
# and is reshaped by it. Items 12, 16, 28 and 30 key that two-way relation.
#
# The single most testable line here is PAU-4.B.1.e, because it records a rule
# being ELIMINATED AND THEN REINSTATED. A student who has only learned that
# Russia's rules restrict competition will read the reinstatement backwards. The
# framework says the elimination and the reinstatement both AFFECTED regional
# parties and independent candidates, and single-member districts are the only
# route by which either can win, so the two changes moved that representation in
# opposite directions. Items 8 and 20-22 key exactly that.
#
