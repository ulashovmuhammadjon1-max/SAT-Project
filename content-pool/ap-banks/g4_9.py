# AP HUMAN GEOGRAPHY 4.9 Challenges to Sovereignty -- 30 questions
# CED Course Framework V.1, Unit 4. Enduring understanding SPS-4, "Political,
# economic, cultural, or technological changes can challenge state
# sovereignty." Learning objective SPS-4.B, "Explain how political, economic,
# cultural, and technological changes challenge state sovereignty."
#
# Essential knowledge -- four statements:
#   SPS-4.B.1  Devolution occurs when states fragment into autonomous regions;
#              subnational political-territorial units, such as those within
#              Spain, Belgium, Canada, and Nigeria; or when states disintegrate,
#              as happened in Sudan and the former Soviet Union.
#   SPS-4.B.2  Advances in communication technology have facilitated devolution,
#              supranationalism, and democratization.
#   SPS-4.B.3  Global efforts to address transnational and environmental
#              challenges and to create economies of scale, trade agreements,
#              and military alliances help to further supranationalism.
#   SPS-4.B.4  Supranational organizations -- including the United Nations (UN),
#              North Atlantic Treaty Organization (NATO), European Union (EU),
#              Association of Southeast Asian Nations (ASEAN), Arctic Council,
#              and African Union -- can challenge state sovereignty by limiting
#              the economic or political actions of member states.
#
# THE ORGANISING IDEA of this topic is that sovereignty is squeezed from two
# directions at once. Devolution moves authority DOWN from the state to regions;
# supranationalism moves authority UP from the state to bodies above it. Both
# leave the state holding less, and SPS-4.B.2 says the same technological change
# facilitated both. Items 7, 17, 21 and 29 are built on that two-directional
# reading, because a student who has only met devolution will read this topic as
# a repeat of 4.8 rather than as its complement.
#
# WHAT SPS-4.B.4 ACTUALLY CLAIMS is narrower than students assume: supranational
# organizations CAN CHALLENGE sovereignty BY LIMITING THE ECONOMIC OR POLITICAL
# ACTIONS of member states. It does not say they abolish sovereignty, override
# it, or govern member states. A state that has agreed to a limit has exercised
# sovereignty in agreeing, which is why the challenge is real but partial. Items
# 14, 15, 16, 22, 23 and 30 all rest on that wording.
#
# COUNTRIES AND ORGANIZATIONS ARE NAMED HERE, unlike in 4.7 and 4.8, because
# THIS statement names them. Spain, Belgium, Canada, Nigeria, Sudan and the
# former Soviet Union appear in SPS-4.B.1 and the six organizations appear in
# SPS-4.B.4; nothing outside those lists is asserted about a real place.
#
# Three items carry a real `table=`. FIVE choices (A-E).
