# AP HUMAN GEOGRAPHY 5.9 The Global System of Agriculture -- 30 questions
# CED Course Framework V.1, Unit 5. Enduring understanding PSO-5, "Availability
# of resources and cultural practices influence agricultural practices and land
# use patterns." Learning objective PSO-5.E, "Explain the interdependence among
# regions of agricultural production and consumption."
#
# Essential knowledge -- three statements:
#   PSO-5.E.1  Food and other agricultural products are part of a global supply
#              chain.
#   PSO-5.E.2  Some countries have become highly dependent on one or more export
#              commodities.
#   PSO-5.E.3  The main elements of global food distribution networks are
#              affected by political relationships, infrastructure, and patterns
#              of world trade.
#
# THE OBJECTIVE'S WORD IS INTERDEPENDENCE, and it runs both ways. Producing
# regions depend on consuming regions for income, and consuming regions depend
# on producing regions for food they do not grow. But the dependence is NOT
# SYMMETRICAL, and item 18 keys on that: a buyer with several possible suppliers
# can substitute, while a country whose export earnings rest on one commodity
# cannot. Interdependence describes the relationship; bargaining power describes
# who can walk away from it, and the two are different questions.
#
# PSO-5.E.2's "SOME COUNTRIES" is a hedge and item 3 respects it. The statement
# says some countries have become highly dependent on one or more export
# commodities -- not all producing countries, and not permanently. No item here
# names a real country as commodity-dependent, because the composition of a
# country's exports changes and a claim true when written can be false when read.
# The two data items use lettered countries for exactly that reason.
#
# PSO-5.E.3 IS A LIST OF THREE FORCES and each gets its own items:
#   political relationships   embargoes, sanctions, alliances, trade agreements
#                             -- a route can be closed by a decision (items 8,
#                             11, 22)
#   infrastructure            ports, roads, storage, refrigeration -- a route can
#                             be closed by the absence of a road (items 9, 12,
#                             20, 21, 28)
#   patterns of world trade   tariffs, subsidies, established trading
#                             relationships (items 10, 13)
# Item 25 requires the three to be told apart, which is the skill the statement's
# structure is asking for.
#
# THE DISTINCTION MOST WORTH TEACHING HERE, and the one item 24 keys on, is food
# SECURITY against food SELF-SUFFICIENCY. A country can be secure without being
# self-sufficient, if it can reliably buy what it does not grow; and it can be
# self-sufficient and insecure, if its own harvest fails. PSO-5.E.1's global
# supply chain is what makes the first possible and PSO-5.E.3's three forces are
# what make it fragile.
#
# NO REAL COUNTRY IS NAMED ANYWHERE IN THIS MODULE.
#
# Three items carry a real `table=`. FIVE choices (A-E).
